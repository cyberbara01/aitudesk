// Строки раздела «Напоминания» и фразы о напоминаниях, которые показывает и редактор заметки. Без длинных тире:
// правило автора. Сроки в винительном падеже («за 2 часа», «раз в 5 минут»), числа через plural() из ru.ts.
import { plural } from "./ru";

const DAY = 24 * 60;
const WEEK = 7 * DAY;

/** Единицы после числа в «за …», «раз в …»: «1 минуту», «2 часа», «5 дней». */
const units = {
  minutes: (n: number) => plural(n, "минуту", "минуты", "минут"),
  hours: (n: number) => plural(n, "час", "часа", "часов"),
  days: (n: number) => plural(n, "день", "дня", "дней"),
};

/** Срок после «за»: «15 минут», «1 час», «3 часа», «2 дня», «неделю», «2 недели». */
function span(minutes: number): string {
  if (minutes % WEEK === 0) {
    const n = minutes / WEEK;
    return n === 1 ? "неделю" : `${n} ${plural(n, "неделю", "недели", "недель")}`;
  }
  if (minutes % DAY === 0) return `${minutes / DAY} ${units.days(minutes / DAY)}`;
  if (minutes % 60 === 0) return `${minutes / 60} ${units.hours(minutes / 60)}`;
  return `${minutes} ${units.minutes(minutes)}`;
}

/** Интервал повтора: «каждые 15 минут», «каждый час», «каждые 3 часа», «раз в день», «каждые 2 дня», «раз в неделю». */
function every(minutes: number): string {
  if (minutes === WEEK) return "раз в неделю";
  if (minutes % DAY === 0) {
    const n = minutes / DAY;
    return n === 1 ? "раз в день" : `каждые ${n} ${units.days(n)}`;
  }
  if (minutes % 60 === 0) {
    const n = minutes / 60;
    return n === 1 ? "каждый час" : `${plural(n, "каждый", "каждые", "каждые")} ${n} ${units.hours(n)}`;
  }
  return minutes === 1 ? "каждую минуту" : `${plural(minutes, "каждую", "каждые", "каждые")} ${minutes} ${units.minutes(minutes)}`;
}

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/**
 * Что придёт по настройкам для одного дедлайна, без примера: «За 1 день, потом каждые 3 часа и в момент
 * дедлайна» (подсказка в редакторе заметки). `repeat` = 0, если повторов не будет. Пустая строка, если ничего.
 */
export function deadlinePlan(first: number, repeat: number, atDeadline: boolean): string {
  const parts: string[] = [];
  if (first > 0) parts.push(`за ${span(first)}${repeat > 0 ? `, потом ${every(repeat)}${atDeadline ? "" : " до дедлайна"}` : ""}`);
  if (atDeadline) parts.push("в момент дедлайна");
  return cap(parts.join(" и "));
}

