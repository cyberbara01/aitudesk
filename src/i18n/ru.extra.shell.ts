/** «1 виджет», «2 виджета», «5 виджетов». */
const widgets = (n: number) => {
  const d = n % 10;
  const dd = n % 100;
  const word = d === 1 && dd !== 11 ? "виджет" : d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? "виджета" : "виджетов";
  return `${n} ${word}`;
};

