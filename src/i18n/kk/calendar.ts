/** The month in the dative case, for «16 қазанға арналған жазба» (the suffix follows the word's vowels and end). */
const DATIVE: Record<string, string> = {
  қаңтар: "қаңтарға",
  ақпан: "ақпанға",
  наурыз: "наурызға",
  сәуір: "сәуірге",
  мамыр: "мамырға",
  маусым: "маусымға",
  шілде: "шілдеге",
  тамыз: "тамызға",
  қыркүйек: "қыркүйекке",
  қазан: "қазанға",
  қараша: "қарашаға",
  желтоқсан: "желтоқсанға",
};
const dative = (day: string) => day.replace(/(\S+)$/, (w) => DATIVE[w] ?? w);

